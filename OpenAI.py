from openai import OpenAI
import os

client = OpenAI(api_key=os.getenv("OPENAI_API_KEY"))


def get_ai_analysis(df):

    # Лучше не отправлять огромный dataframe целиком
    # Для начала ограничим размер
    data_text = df.to_csv(index=False)

    prompt = f"""
Ты рекламный аналитик.

Проанализируй данные по сайтам и рекламным каналам.

Найди:
- рост и падение показателей;
- аномалии;
- изменение рекламных бюджетов;
- изменение visits;
- изменения медиамикса;
- наиболее сильные изменения по сайтам;
- наиболее сильные изменения по каналам.

Сравнивай сопоставимые периоды.

В конце обязательно дай:
1. ТОП-5 ключевых выводов
2. Рекомендации для клиента

Не придумывай показатели, которых нет в данных.
Все числовые выводы должны основываться только на переданных данных.

Данные:

{data_text}
"""

    response = client.responses.create(
        model="gpt-5.6",
        input=prompt
    )

    return response.output_text